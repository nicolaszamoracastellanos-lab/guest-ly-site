export const HOME_COPY = { en, es };
export type { HomeCopy };

/** 8 -> "8:00 AM" (en) or "8:00" (es). */
export function hourLabel(h: number, lang: "en" | "es"): string {
  if (lang === "es") return `${h}:00`;
  const ap = h < 12 ? "AM" : "PM";
  const h12 = h % 12 === 0 ? 12 : h % 12;
  return `${h12}:00 ${ap}`;
}

/** The recap in one line, for Settings. */
export function recapLine(c: HomeCopy, r: { cadence: "daily" | "weekly" | "needed"; weekday: number; hour: number }, lang: "en" | "es"): string {
  if (r.cadence === "needed") return c.recapNeeded;
  const h = hourLabel(r.hour, lang);
  return r.cadence === "daily" ? c.recapDaily(h) : c.recapWeekly(c.weekdays[r.weekday] ?? c.weekdays[1], h);
}
